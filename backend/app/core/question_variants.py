def prepared_variants(base_code: str) -> list[dict[str, Any]]:
    """Три проверяемых варианта семьи: текущий вопрос и два параметрических."""
    family = BACKEND_FAMILIES[base_code]
    base = next(q for q in PREDEFINED_QUESTIONS if q["code"] == base_code)
    result = [{**base, "family_code": base_code, "variant_id": "v1", "skill": family["skill"], "rubric": family["rubric"]}]
    for index, case in enumerate(family["cases"], start=2):
        choices = case.get("options", family.get("options"))
        assert choices is not None
        result.append({
            "code": f"{base_code}-V{index}",
            "family_code": base_code,
            "variant_id": f"v{index}",
            "specialization": base["specialization"],
            "grade": base["grade"],
            "topic": base["topic"],
            "skill": family["skill"],
            "rubric": family["rubric"],
            "question_type": "single_choice",
            "question_text": family["template"].format(**case["params"]),
            "options": [{"id": chr(65 + i), "text": text} for i, text in enumerate(choices)],
            "correct_answers": [chr(65 + case["answer"])],
            "explanation": case["explanation"],
            "weight": base["weight"],
            "parameters": case["params"],
        })
    return result


def variant_for_attempt(base_code: str, previous_attempts: int) -> dict[str, Any]:
    """Выбрать очередной вариант; соседние попытки не повторяют его."""
    if previous_attempts < 0:
        raise ValueError("Число предыдущих попыток не может быть отрицательным")
    variants = prepared_variants(base_code)
    return variants[previous_attempts % len(variants)]
