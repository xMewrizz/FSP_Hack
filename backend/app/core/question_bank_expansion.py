def _make_question(code: str, family: dict[str, Any], version: int) -> dict[str, Any]:
    text, answer, explanation = family["cases"][version - 1]
    grade = {"JR": "junior", "MID": "middle", "SR": "senior"}[code.split("-")[1]]
    options = family["options"]
    offset = hashlib.sha256(code.encode("ascii")).digest()[0] % len(options)
    shift = (answer + offset + version) % len(options)
    rotated_options = options[shift:] + options[:shift]
    answer_text = options[answer]
    return {
        "code": code if version == 1 else f"{code}-V{version}",
        "family_code": code,
        "variant_id": f"v{version}",
        "specialization": "Backend",
        "grade": grade,
        "topic": family["topic"],
        "skill": family["skill"],
        "rubric": family["rubric"],
        "question_type": "single_choice",
        "question_text": text,
        "options": [{"id": chr(65 + index), "text": option} for index, option in enumerate(rotated_options)],
        "correct_answers": [chr(65 + rotated_options.index(answer_text))],
        "explanation": explanation,
        "weight": {"junior": 1.0, "middle": 1.5, "senior": 2.0}[grade],
    }


def extra_base_questions() -> list[dict[str, Any]]:
    return [_make_question(code, family, 1) for code, family in EXTRA_FAMILIES.items()]


def extra_prepared_variants(code: str) -> list[dict[str, Any]]:
    return [_make_question(code, EXTRA_FAMILIES[code], version) for version in (1, 2, 3)]
