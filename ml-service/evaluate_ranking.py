"""Посмотреть порядок кандидатов B-14 на файлах B-03 без запуска backend."""

from __future__ import annotations

import json
from pathlib import Path
import sys


REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "backend"))
from app.core.ranking import baseline_rank, rank_candidates  # noqa: E402


DATA_DIR = REPO_ROOT / "ml-service" / "data" / "synthetic_v1"
REPORT_PATH = REPO_ROOT / "docs" / "09-ranking-review.md"


def build_report() -> str:
    candidates = json.loads((DATA_DIR / "candidates.json").read_text(encoding="utf-8"))
    needs = json.loads((DATA_DIR / "needs.json").read_text(encoding="utf-8"))
    lines = [
        "# Проверка порядка кандидатов на синтетических данных",
        "",
        "Первый расчёт B-14 выполнен на наборе B-03 без API и базы. Здесь пять запросов работодателя и 60 вымышленных профилей; отметки о пройденном тесте и достижения ФСП в профилях тоже синтетические. Баллы нужны только для порядка кандидатов внутри группы: это не процент соответствия и не вероятность найма. Независимых оценок релевантности пока нет, поэтому сравнение с базовой сортировкой показывает разницу в порядке, а не улучшение качества.",
        "",
        "## Правила",
        "",
        "Сначала оставляем только ту же специализацию и тот же грейд. Кандидаты с подтверждённым результатом теста образуют основную группу; кандидаты только с заявленным грейдом идут отдельно. Другой грейд не подставляется автоматически. В каждой группе считаем до 55 баллов за навыки с учётом веса требования, до 20 за результат теста, до 10 за формат работы и город, до 10 за сопоставимые ожидания зарплаты и до 5 за подтверждённое достижение ФСП. Отсутствие истории ФСП не отнимает базовые баллы. Навык берём из явного списка кандидата, а не угадываем по тексту резюме. Зарплаты сравниваем только при одинаковой пометке «до вычета» или «на руки». Для удалённой работы город не учитываем.",
        "",
        "Это предварительные веса команды, а не числа из ТЗ и не обученная модель. Навыки получают наибольшую долю, потому что запрос работодателя прежде всего описывает нужный стек; результат теста влияет на порядок внутри подтверждённой группы; формат и зарплата помогают различать практические ограничения; ФСП даёт небольшой дополнительный вес и не меняет категорию. Перед использованием в продукте веса нужно проверить по независимой разметке B-19.",
        "",
        "Простая базовая сортировка использует те же группы, но внутри них смотрит только число совпавших навыков. При равенстве порядок задаёт ID профиля. Это сравнение алгоритмов на одних входных данных, без выдуманных меток качества.",
        "",
        "## Результаты первого прогона",
        "",
        "| Запрос | Подтверждены тестом | Только заявили грейд | Первые 3 в основной группе | Первые 3 отдельно | Первые 3 простой сортировки |",
        "|---|---:|---:|---|---|---|",
    ]
    for need in needs:
        ranked = rank_candidates(need, candidates)
        baseline = baseline_rank(need, candidates)
        show = lambda items: ", ".join(items) if items else "нет"
        lines.append(
            f"| {need['title']} | {len(ranked['confirmed'])} | {len(ranked['unconfirmed'])} | "
            f"{show([item['candidate_code'] for item in ranked['confirmed'][:3]])} | "
            f"{show([item['candidate_code'] for item in ranked['unconfirmed'][:3]])} | "
            f"{show(baseline['confirmed'][:3])} |"
        )
    lines.extend((
        "",
        "У Frontend и DevOps в синтетическом наборе нет подтверждённого грейда: для этих направлений тест пока не открыт. Поэтому основная группа там пуста, а кандидаты видны отдельно. Это ожидаемое состояние данных, а не ошибка сортировки.",
        "",
        "## Как читать отдельный результат",
        "",
    ))
    for need in needs:
        ranked = rank_candidates(need, candidates)
        first = (ranked["confirmed"] or ranked["unconfirmed"])[0]
        group = "подтверждён" if first["group"] == "confirmed" else "грейд только заявлен"
        parts = first["parts"]
        lines.append(
            f"- **{need['title']} — {first['candidate_code']}** ({group}): {first['points']} балла. "
            f"Навыки {parts['skills']}, тест {parts['test']}, формат и город {parts['work']}, "
            f"зарплата {parts['salary']}, ФСП {parts['fsp']}. "
            f"Совпали: {', '.join(first['matched_skills']) or 'нет'}; "
            f"не хватает: {', '.join(first['missing_skills']) or 'нет'}."
        )
    lines.extend((
        "",
        "Следующий шаг B-14 — после B-00 и готовности формы потребности подключить этот расчёт к API и проверить на реальных записях. Для оценки Precision@3 и выбора весов нужны независимые метки релевантности (B-19). Сейчас B-14 не закрыта.",
        "",
    ))
    return "\n".join(lines)


if __name__ == "__main__":
    REPORT_PATH.write_text(build_report(), encoding="utf-8", newline="\n")
    print(REPORT_PATH)
