"""Посмотреть порядок кандидатов B-14 на файлах B-03 без запуска backend."""

from __future__ import annotations

import json
from pathlib import Path
import sys


REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "backend"))
from app.core.ranking import baseline_rank, rank_candidates  # noqa: E402


DATA_DIR = REPO_ROOT / "ml-service" / "data" / "synthetic_v1"
REPORT_PATH = REPO_ROOT / "docs" / "09-ranking-review.md"


def build_report() -> str:
    candidates = json.loads((DATA_DIR / "candidates.json").read_text(encoding="utf-8"))
    needs = json.loads((DATA_DIR / "needs.json").read_text(encoding="utf-8"))
    lines = [
        "# Проверка порядка кандидатов на синтетических данных",
        "",
        "Расчёт B-14 выполнен на наборе B-03. Здесь пять запросов работодателя и 60 вымышленных профилей; отметки о пройденном тесте и достижения ФСП в профилях тоже синтетические. Баллы нужны только для порядка кандидатов: это не процент соответствия и не вероятность найма. Независимых оценок релевантности пока нет, поэтому сравнение с базовой сортировкой показывает разницу в порядке, а не улучшение качества.",
        "",
        "## Правила",
        "",
        "Формула оставляет только кандидатов с подтверждённым грейдом той же специализации и того же уровня. Заявленный грейд допуска не даёт. Другой грейд не подставляется. Среди допущенных считаем до 55 баллов за навыки с учётом веса требования, до 20 за результат теста, до 10 за формат работы и город, до 10 за сопоставимые ожидания зарплаты и до 5 за подтверждённое достижение ФСП. Отсутствие истории ФСП не отнимает базовые баллы и не исключает кандидата. Навык берём из явного списка кандидата, а не угадываем по тексту резюме. Зарплату читаем по полям `salary_tax_type` или `salary_basis` и сравниваем только при одинаковой пометке «до вычета» или «на руки». Для удалённой работы город не учитываем. Открытость профиля в этот файловый прогон не входит: у вымышленных анкет нет согласий.",
        "",
        "Это предварительные веса команды, а не числа из ТЗ и не обученная модель. Навыки получают наибольшую долю, потому что запрос работодателя прежде всего описывает нужный стек; результат теста влияет на порядок внутри подтверждённой категории; формат и зарплата помогают различать практические ограничения; ФСП даёт небольшой дополнительный вес и не меняет категорию. Перед использованием в продукте веса нужно проверить по независимой разметке B-19.",
        "",
        "Простая базовая сортировка оставляет тех же кандидатов, но внутри списка смотрит только число совпавших навыков. При равенстве порядок задаёт ID профиля. Это сравнение алгоритмов на одних входных данных, без выдуманных меток качества.",
        "",
        "## Результаты прогона",
        "",
        "| Запрос | Подтверждены тестом | Первые 3 | Первые 3 простой сортировки |",
        "|---|---:|---|---|",
    ]
    for need in needs:
        ranked = rank_candidates(need, candidates)
        baseline = baseline_rank(need, candidates)
        show = lambda items: ", ".join(items) if items else "нет"
        lines.append(
            f"| {need['title']} | {len(ranked)} | "
            f"{show([item['candidate_code'] for item in ranked[:3]])} | "
            f"{show(baseline[:3])} |"
        )
    lines.extend((
        "",
        "У Frontend и DevOps в синтетическом наборе нет подтверждённого грейда: для этих направлений тест пока не открыт. Поэтому выдача по этим потребностям пустая. Люди, которые только заявили грейд, в список не попадают. Это ожидаемое состояние данных, а не ошибка сортировки.",
        "",
        "## Как читать отдельный результат",
        "",
    ))
    empty_titles: list[str] = []
    for need in needs:
        ranked = rank_candidates(need, candidates)
        if not ranked:
            empty_titles.append(need["title"])
            continue
        first = ranked[0]
        parts = first["parts"]
        lines.append(
            f"- **{need['title']} — {first['candidate_code']}** (подтверждён): {first['points']} балла. "
            f"Навыки {parts['skills']}, тест {parts['test']}, формат и город {parts['work']}, "
            f"зарплата {parts['salary']}, ФСП {parts['fsp']}. "
            f"Совпали: {', '.join(first['matched_skills']) or 'нет'}; "
            f"не хватает: {', '.join(first['missing_skills']) or 'нет'}."
        )
    if empty_titles:
        lines.append("")
        lines.append(
            "Пустая выдача: "
            + ", ".join(empty_titles)
            + ". В наборе нет кандидата с подтверждённым грейдом этой специализации и уровня."
        )
    lines.extend((
        "",
        "Это пересчёт формулы на файлах B-03. API подбора теперь использует ту же формулу; порядок и баллы проверены отдельным тестом. Для оценки качества на реальных кандидатах нужны дополнительные запросы и метки релевантности (B-19).",
        "",
    ))
    return "\n".join(lines)


if __name__ == "__main__":
    REPORT_PATH.write_text(build_report(), encoding="utf-8", newline="\n")
    print(REPORT_PATH)
